// Database connections. The same Drizzle schema and SQL migrations run on two drivers:
//   - node-postgres, when DATABASE_URL is set;
//   - PGlite (embedded Postgres compiled to WASM), otherwise: on disk under PGLITE_DIR
//     (default .data/pglite) for dev/e2e, or in memory for tests.
import { mkdirSync } from 'node:fs';
import path from 'node:path';
import { PGlite } from '@electric-sql/pglite';
import { drizzle as drizzlePg } from 'drizzle-orm/node-postgres';
import { migrate as migratePg } from 'drizzle-orm/node-postgres/migrator';
import type { PgDatabase, PgQueryResultHKT } from 'drizzle-orm/pg-core';
import { drizzle as drizzlePglite } from 'drizzle-orm/pglite';
import { migrate as migratePglite } from 'drizzle-orm/pglite/migrator';
import pg from 'pg';
import * as schema from './schema';

/** Driver-independent Drizzle database handle used by repositories. */
export type Db = PgDatabase<PgQueryResultHKT, typeof schema>;

export interface Database {
  db: Db;
  driver: 'pglite' | 'postgres';
  /** Applies pending SQL migrations from /drizzle (idempotent). */
  migrate(): Promise<void>;
  close(): Promise<void>;
}

/** Folder with the SQL migrations generated by drizzle-kit. Resolved from the project root. */
export const MIGRATIONS_FOLDER = path.join(process.cwd(), 'drizzle');

export const DEFAULT_PGLITE_DIR = '.data/pglite';

export function createPgliteDatabase(client: PGlite = new PGlite()): Database {
  const db = drizzlePglite({ client, schema });
  return {
    db,
    driver: 'pglite',
    migrate: () => migratePglite(db, { migrationsFolder: MIGRATIONS_FOLDER }),
    close: () => client.close(),
  };
}

export function createPostgresDatabase(connectionString: string): Database {
  const pool = new pg.Pool({ connectionString, max: 10 });
  const db = drizzlePg({ client: pool, schema });
  return {
    db,
    driver: 'postgres',
    migrate: () => migratePg(db, { migrationsFolder: MIGRATIONS_FOLDER }),
    close: () => pool.end(),
  };
}

/** Opens the database configured by the environment (DATABASE_URL, else PGlite at PGLITE_DIR). */
export function openDatabaseFromEnv(env: NodeJS.ProcessEnv = process.env): Database {
  if (env.DATABASE_URL) return createPostgresDatabase(env.DATABASE_URL);
  // The data directory is runtime state, not a build input: keep Next's file tracing out of it.
  const dataDir = path.resolve(/*turbopackIgnore: true*/ env.PGLITE_DIR || DEFAULT_PGLITE_DIR);
  mkdirSync(path.dirname(dataDir), { recursive: true });
  return createPgliteDatabase(new PGlite(dataDir));
}
